#[test]
fn corrupt_value_info_is_an_error_not_an_empty_name() {
    // ValueInfoProto { name: "X", type: <truncated TypeProto> }
    let mut vi = bytes_field(1, b"X");
    // field 2 (type) whose payload declares an inner length running past its own end
    vi.extend(bytes_field(2, &[0x0A, 0x7F, 0x00]));
    let err = parse_value_info_proto(&vi).expect_err("corrupt TypeProto must be reported");
    assert!(err.contains("EOF"), "unexpected message: {err}");

    // And the graph-level path propagates it rather than yielding an input named "".
    let graph_bytes = bytes_field(11, &vi);
    let err = parse_graph(&graph_bytes).expect_err("corrupt input must be reported");
    assert!(err.contains("EOF"), "unexpected message: {err}");
}

