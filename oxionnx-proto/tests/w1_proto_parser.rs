// [a2-2] Recursion depth limit
// ─────────────────────────────────────────────────────────────────

/// Build `levels` nested subgraph attributes: graph → node → attribute(g) → graph → …
fn nested_subgraph(levels: u32) -> Vec<u8> {
    let mut graph = bytes_field(2, b"leaf");
    for level in 0..levels {
        let mut attr = bytes_field(1, b"body");
        attr.extend(bytes_field(6, &graph)); // AttributeProto.g
        attr.extend(varint_field(20, 5)); // AttributeType::GRAPH
        let mut node = bytes_field(4, b"Loop");
        node.extend(bytes_field(5, &attr));
        graph = bytes_field(1, &node);
        graph.extend(bytes_field(2, format!("g{level}").as_bytes()));
    }
    graph
}

#[test]
fn moderate_subgraph_nesting_still_parses() {
    let g = parse_graph(&nested_subgraph(32)).expect("32 levels must parse");
    assert_eq!(g.nodes.len(), 1);
}

#[test]
fn excessive_subgraph_nesting_is_an_error_not_a_stack_overflow() {
    let deep = nested_subgraph(4096);
    let err = parse_graph(&deep).expect_err("4096 levels must be rejected");
    assert!(err.contains("depth"), "unexpected message: {err}");

    // Same through the top-level model entry point.
    let model_bytes = bytes_field(7, &deep);
    let err = parse_model(&model_bytes).expect_err("deep model must be rejected");
    assert!(err.contains("depth"), "unexpected message: {err}");
}

