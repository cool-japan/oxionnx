// ─────────────────────────────────────────────────────────────────
// Encoding helpers
// ─────────────────────────────────────────────────────────────────

fn encode_varint(mut val: u64) -> Vec<u8> {
    let mut buf = Vec::new();
    loop {
        let byte = (val & 0x7F) as u8;
        val >>= 7;
        if val == 0 {
            buf.push(byte);
            return buf;
        }
        buf.push(byte | 0x80);
    }
}

fn tag(field: u32, wire: u8) -> Vec<u8> {
    encode_varint(((field as u64) << 3) | u64::from(wire))
}

fn bytes_field(field: u32, data: &[u8]) -> Vec<u8> {
    let mut buf = tag(field, 2);
    buf.extend(encode_varint(data.len() as u64));
    buf.extend(data);
    buf
}

fn varint_field(field: u32, val: u64) -> Vec<u8> {
    let mut buf = tag(field, 0);
    buf.extend(encode_varint(val));
    buf
}

/// A length-delimited field whose declared length is `u64::MAX` (10-byte varint).
fn hostile_len_field(field: u32) -> Vec<u8> {
    let mut buf = tag(field, 2);
    buf.extend([0xFF; 9]);
    buf.push(0x01);
    buf
}

