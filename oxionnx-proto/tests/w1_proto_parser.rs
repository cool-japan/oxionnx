#[test]
fn attribute_floats_accept_unpacked_encoding() {
    // This is what the real ONNX writer emits: one (field 7, wire type 5) tag per value.
    let attr = parse_attribute(&REF_FLOATS_ATTR).expect("floats attribute must parse");
    assert_eq!(attr.name, "scales");
    assert_eq!(attr.value.attr_type, 6); // AttributeType::FLOATS
    assert_eq!(attr.value.floats, vec![1.0, 2.5, -0.5]);
}

#[test]
fn attribute_floats_accept_packed_encoding() {
    let mut packed = Vec::new();
    for v in [1.0f32, 2.5, -0.5] {
        packed.extend(v.to_le_bytes());
    }
    let mut attr_bytes = bytes_field(1, b"scales");
    attr_bytes.extend(bytes_field(7, &packed));
    let attr = parse_attribute(&attr_bytes).expect("packed floats must parse");
    assert_eq!(attr.value.floats, vec![1.0, 2.5, -0.5]);
}

#[test]
fn tensor_typed_fields_accept_unpacked_encoding() {
    // float_data / int32_data / int64_data / double_data / uint64_data, all unpacked.
    let mut t_bytes = varint_field(1, 2); // dims = [2] (unpacked, as ONNX emits)
    t_bytes.extend(tag(4, 5));
    t_bytes.extend(1.5f32.to_le_bytes());
    t_bytes.extend(tag(4, 5));
    t_bytes.extend((-2.5f32).to_le_bytes());
    t_bytes.extend(varint_field(5, 9));
    t_bytes.extend(varint_field(7, 11));
    t_bytes.extend(tag(10, 1));
    t_bytes.extend(0.25f64.to_le_bytes());
    t_bytes.extend(varint_field(11, 300));

    let t = parse_tensor_proto(&t_bytes).expect("unpacked tensor fields must parse");
    assert_eq!(t.dims, vec![2]);
    assert_eq!(t.float_data, vec![1.5, -2.5]);
    assert_eq!(t.int32_data, vec![9]);
    assert_eq!(t.int64_data, vec![11]);
    assert_eq!(t.double_data, vec![0.25]);
    assert_eq!(t.uint64_data, vec![300]);
}

