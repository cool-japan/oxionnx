#[test]
fn streaming_header_uses_the_same_field_numbers_as_the_eager_parser() {
    let mut header_seen = false;
    let mut opsets: Vec<(String, i64)> = Vec::new();
    let mut first_event: Option<&'static str> = None;
    let mut parser = StreamingParser::new(Cursor::new(REF_MODEL.to_vec()));
    parser
        .parse(|event| {
            match event {
                ParseEvent::ModelHeader {
                    ir_version,
                    model_version,
                    producer_name,
                    producer_version,
                    ..
                } => {
                    assert_eq!(ir_version, 8);
                    assert_eq!(model_version, 42);
                    assert_eq!(producer_name, "oxionnx-test");
                    assert_eq!(producer_version, "9.9");
                    header_seen = true;
                    first_event.get_or_insert("ModelHeader");
                }
                ParseEvent::OpsetImport { domain, version } => {
                    opsets.push((domain, version));
                    first_event.get_or_insert("OpsetImport");
                }
                _ => {
                    first_event.get_or_insert("other");
                }
            }
            Ok(())
        })
        .expect("streaming parse must succeed");
    assert!(header_seen, "ModelHeader event must be emitted");
    assert_eq!(first_event, Some("ModelHeader"), "header must come first");
    // Real ONNX writers put opset_import (field 8) after the graph (field 7), so the
    // imports arrive as their own events rather than inside the header.
    assert_eq!(opsets, vec![(String::new(), 26)]);
}

